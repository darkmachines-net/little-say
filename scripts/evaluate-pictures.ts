/** @file Runs opt-in billable picture checks and saves construction or animal source-comparison assets and a contact sheet. */

import { mkdir, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { loadDevelopmentEnv, withDevelopmentApiKey } from './dev-config';
import { openAIPictureProvider, type PictureMetric } from '../apps/server/src/pictures/provider';
import { PictureJobs } from '../apps/server/src/pictures/jobs';
import { downloadCatalogPicture, searchPictures } from '../apps/server/src/pictures/catalog';

if (process.argv.includes('--catalog')) {
  for (const [word, style] of [['dumper truck', 'color'], ['cow', 'color'], ['tractor', 'line']] as const) {
    const entry = searchPictures(word, style)[0];
    try { const bytes = await downloadCatalogPicture(entry); console.log(JSON.stringify({ id: entry.id, bytes: bytes.length })); }
    catch (error) { console.error(JSON.stringify({ id: entry.id, error: (error as Error).message })); process.exitCode = 1; }
  }
  process.exit(process.exitCode ?? 0);
}

const env = await withDevelopmentApiKey(await loadDevelopmentEnv(fileURLToPath(new URL('../', import.meta.url))));
const usage: PictureMetric[] = [];
const provider = openAIPictureProvider(env, metric => { usage.push(metric); console.log(JSON.stringify(metric)); });
if (!provider) throw new Error('Configure the backend API key before running this billable evaluation.');
const generate = process.argv.includes('--generate');
const animals = process.argv.includes('--animals');
const style = 'color';
const directory = resolve('artifacts/picture-evaluation', animals ? 'animals' : style);
await mkdir(directory, { recursive: true });
const jobs = new PictureJobs(resolve('.cache/picture-evaluation'), provider, generate);
const labels = animals ? ['Cow', 'Sheep', 'Horse', 'Rabbit', 'Chicken', 'Duck'] : ['Dump truck', 'Concrete truck', 'Excavator', 'Bulldozer', 'Crane truck', 'Road roller'];
const emojis = animals ? ['🐄', '🐑', '🐎', '🐇', '🐓', '🦆'] : ['🚚', '🚚', '🚜', '🚜', '🏗️', '🚜'];
const library = [];
// Use the live chicken symbol; the library's exact "chicken" name refers to prepared food.
if (animals) for (const [index, id] of ['mulberry-806', 'mulberry-2538', 'mulberry-1682', 'mulberry-2351', 'mulberry-463', 'mulberry-981'].entries()) {
  const asset = await jobs.library(id);
  await writeFile(resolve(directory, `library-${index}.png`), asset.bytes);
  library.push({ label: labels[index], picture: asset.picture });
}
const start = Date.now();
const analysis = await provider.analyze({ tiles: labels.map((label, index) => ({ id: String(index), label, language: 'en-US', emoji: emojis[index], instruction: '' })) });
console.log(JSON.stringify({ operation: 'analyze', milliseconds: Date.now() - start, accurateEmoji: analysis.tiles.filter(tile => tile.concept.emojiAccurate).map(tile => tile.id) }));
const results: { label: string; state: string; kind?: string; assetId?: string; milliseconds: number }[] = [];
const cards: Parameters<PictureJobs['review']>[0] = [];
try {
  await Promise.all(analysis.tiles.map(async tile => {
    const started = Date.now(); const id = randomUUID();
    let job = await jobs.start({ requestId: id, draftId: animals ? 'animal-comparison' : 'construction-evaluation', tileId: tile.id, concept: tile.concept, style, mode: animals ? 'generated' : 'auto', allowGeneration: generate, regenerate: false, neighbors: analysis.tiles.filter(other => other.id !== tile.id).map(other => other.concept.description) });
    while (job.state === 'working' || job.state === 'queued') { await new Promise(resolve => setTimeout(resolve, 1000)); job = (await jobs.status(id))!; }
    const picture = job.result;
    const assetId = picture && picture.kind !== 'unresolved' ? picture.assetId : undefined;
    if (assetId) { await writeFile(resolve(directory, `${tile.id}.png`), (await jobs.read(assetId))!); cards.push({ id: tile.id, concept: tile.concept, assetId }); }
    const result = { label: labels[Number(tile.id)], state: job.state, kind: picture?.kind, assetId, milliseconds: Date.now() - started };
    results[Number(tile.id)] = result; console.log(JSON.stringify(result));
  }));
  const rejected = cards.length ? await jobs.review(cards) : [];
  const report = { model: provider.model, style, generationAllowed: generate, milliseconds: Date.now() - start, usage, rejected, results, ...(animals ? { emojis, library } : {}) };
  await writeFile(resolve(directory, 'report.json'), `${JSON.stringify(report, null, 2)}\n`);
  await writeFile(resolve(directory, 'index.html'), `<!doctype html>\n<!-- Generated by scripts/evaluate-pictures.ts for human visual QA. -->\n<html lang="en"><meta charset="utf-8"><title>Picture evaluation</title><style>body{font:20px system-ui;margin:30px;background:#faf8f0}main{display:grid;grid-template-columns:repeat(3,1fr);gap:20px;max-width:1100px}article{background:#d7ece3;padding:20px;border-radius:20px;text-align:center}img{width:100%;height:250px;object-fit:contain}small{display:block}</style><h1>Picture evaluation</h1><main>${results.map((result, index) => `<article>${result.assetId ? `<img src="${index}.png" alt="${result.label}">` : '<p>Needs a picture</p>'}<strong>${result.label}</strong><small>${result.kind ?? result.state}${rejected.includes(String(index)) ? ' · Review rejected' : ''}</small></article>`).join('')}</main></html>`);
  if ((!animals && analysis.tiles.some(tile => tile.concept.emojiAccurate)) || rejected.length || (generate && results.some(result => !result.assetId))) process.exitCode = 1;
} finally { jobs.close(); }
