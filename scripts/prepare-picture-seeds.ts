/** @file Downloads pinned licensed generic symbols, rasterizes them once, and writes digest-verified bundled PNGs plus a review contact sheet. */

import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { genericConcepts } from '../apps/server/src/generic-concepts';
import { catalogPicture, downloadCatalogPicture } from '../apps/server/src/pictures/catalog';
import bundled from '../apps/server/src/pictures/data/picture-seeds.json';
import generated from '../apps/server/src/pictures/data/generated-picture-seeds.json';

const directory = resolve('artifacts/picture-seeds');
await mkdir(directory, { recursive: true });
const output: Record<string, { png: string; digest: string }> = {};
for (const concept of genericConcepts) {
  if (!concept.source || output[concept.source]) continue;
  const entry = catalogPicture(concept.source);
  if (!entry) throw new Error(`Unknown seed source: ${concept.source}`);
  const stored = (bundled as Record<string, { png: string; digest: string }>)[concept.source];
  const png = process.argv.includes('--offline') ? Buffer.from(stored.png, 'base64') : await downloadCatalogPicture(entry);
  if (process.argv.includes('--offline') && createHash('sha256').update(png).digest('hex') !== stored.digest) throw new Error('Bundled picture digest mismatch.');
  output[concept.source] = { png: png.toString('base64'), digest: createHash('sha256').update(png).digest('hex') };
  await writeFile(resolve(directory, `${concept.source}.png`), png);
}
await writeFile(resolve('apps/server/src/pictures/data/picture-seeds.json'), JSON.stringify(output) + '\n');
const figures = genericConcepts.filter(item => item.source).map(item => `<figure><img src="${item.source}.png"><figcaption>${item.id} (${item.source})</figcaption></figure>`);
for (const [meaning, seed] of Object.entries(generated)) {
  const filename = `generated-${meaning.replace(/ /g, '-')}.png`;
  await writeFile(resolve(directory, filename), Buffer.from(seed.png, 'base64'));
  figures.push(`<figure><img src="${filename}"><figcaption>${meaning} (generated, ${seed.quality})</figcaption></figure>`);
}
await writeFile(resolve(directory, 'index.html'), '<!doctype html>\n<!-- Generated by prepare-picture-seeds.ts; licensed source attribution remains in pictures/data/catalog.json. -->\n<meta charset="utf-8"><title>Generic picture seeds</title><style>body{font:18px system-ui;background:#f4f6f0}main{display:grid;grid-template-columns:repeat(5,1fr);gap:16px}img{width:140px;height:140px;object-fit:contain}figure{margin:8px}</style><main>' + figures.join('') + '</main>');
console.log(JSON.stringify({ librarySeeds: Object.keys(output).length, generatedSeeds: Object.keys(generated).length, contactSheet: directory }));
